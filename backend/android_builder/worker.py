def _toolchain_status():
    """Verify executable versions and the exact SDK components required by the template."""
    gradle = shutil.which("gradle")
    java_home = Path(os.environ.get("JAVA_HOME", "/usr/lib/jvm/java-17-openjdk-amd64"))
    java = java_home / "bin/java"
    sdk = Path(os.environ.get("ANDROID_HOME", "/opt/android-sdk"))
    platform = sdk / "platforms/android-35/android.jar"
    build_tools = sdk / "build-tools"
    if not gradle or not java.is_file() or not platform.is_file() or not build_tools.is_dir():
        return None
    try:
        required_tools = next((p for p in build_tools.iterdir() if p.is_dir() and p.name.startswith("35.")), None)
        if required_tools is None or not all((required_tools / name).is_file() for name in ("aapt2", "d8", "zipalign", "apksigner")):
            return None
        gradle_result = subprocess.run([gradle, "--version"], capture_output=True, text=True,
                                       timeout=8, check=False)
        java_result = subprocess.run([str(java), "-version"], capture_output=True, text=True,
                                     timeout=8, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    gradle_text = (gradle_result.stdout or "") + (gradle_result.stderr or "")
    java_text = (java_result.stdout or "") + (java_result.stderr or "")
    if gradle_result.returncode != 0 or "Gradle 8.7" not in gradle_text:
        return None
    if java_result.returncode != 0 or not any(token in java_text for token in ("17.", 'version "17"')):
        return None
    if not any(p.is_dir() for p in build_tools.iterdir()):
        return None
    return {"status": "ready", "gradle": "8.7", "java": "17", "android_sdk": "35"}


@app.get("/ready")
def ready(authorization: str | None = Header(default=None)):
    """Report readiness only to callers holding the builder credential."""
    if not TOKEN:
        raise HTTPException(503, "Android builder authentication is not configured")
    if authorization != f"Bearer {TOKEN}":
        raise HTTPException(401, "Unauthorized")
    status = _toolchain_status()
    if status is None:
        raise HTTPException(503, "Android build toolchain is incomplete or incompatible")
    return status

class _BuildClientDisconnected(Exception):
    """Raised after the caller disconnects while Gradle is running."""


class CleanupFileResponse(FileResponse):
    """Ensure the temporary build directory is removed even on response cancellation."""

    def __init__(self, *args, cleanup_dir: str, **kwargs):
        self.cleanup_dir = cleanup_dir
        super().__init__(*args, **kwargs)

    async def __call__(self, scope, receive, send):
        try:
            await super().__call__(scope, receive, send)
        finally:
            shutil.rmtree(self.cleanup_dir, ignore_errors=True)


async def _stop_process_group(process):
    """Stop Gradle and any child processes it spawned, not just the wrapper process."""
    if process.returncode is not None:
        return
    try:
        os.killpg(process.pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    try:
        await asyncio.wait_for(process.wait(), timeout=PROCESS_TERMINATION_GRACE_SECONDS)
        return
    except asyncio.TimeoutError:
        pass
    try:
        os.killpg(process.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    await process.wait()


async def _run_gradle_build(root: Path, env: dict, log_path: Path, request: Request):
    """Run Gradle without blocking the event loop; kill the whole process group on timeout/disconnect."""
    command = ["gradle", "--no-daemon", "--max-workers=2", "--console=plain", "assembleDebug"]
    started = asyncio.get_running_loop().time()
    with log_path.open("wb") as log:
        process = await asyncio.create_subprocess_exec(
            *command, cwd=root, env=env, stdout=log, stderr=subprocess.STDOUT,
            start_new_session=True, preexec_fn=_limits,
        )
        wait_task = asyncio.create_task(process.wait())
        try:
            while True:
                remaining = BUILD_TIMEOUT - (asyncio.get_running_loop().time() - started)
                if remaining <= 0:
                    await _stop_process_group(process)
                    await wait_task
                    raise HTTPException(504, "APK build timed out")
                done, _ = await asyncio.wait({wait_task}, timeout=min(1.0, remaining))
                if wait_task in done:
                    return_code = wait_task.result()
                    return type("BuildResult", (), {"returncode": return_code})()
                if await request.is_disconnected():
                    await _stop_process_group(process)
                    await wait_task
                    raise _BuildClientDisconnected()
        except BaseException:
            if process.returncode is None:
                await _stop_process_group(process)
            if not wait_task.done():
                await wait_task
            raise


@app.post("/build")
async def build_apk(request: Request, file: UploadFile = File(...), authorization: str | None = Header(default=None)):
    if not TOKEN or authorization != f"Bearer {TOKEN}":
        raise HTTPException(401, "Unauthorized")
    raw = await file.read(MAX_ARCHIVE + 1)
    if len(raw) > MAX_ARCHIVE:
        raise HTTPException(413, "Source archive too large")
    try:
        archive = zipfile.ZipFile(io.BytesIO(raw))
        infos = archive.infolist()
    except (zipfile.BadZipFile, OSError):
        raise HTTPException(422, "Invalid source archive")
    if len(infos) > MAX_FILES:
        raise HTTPException(413, "Too many files")
    total = 0
    clean = []
    seen = set()
    for info in infos:
        name = info.filename
        path = PurePosixPath(name)
        mode = (info.external_attr >> 16) & 0o170000
        if (path.is_absolute() or ".." in path.parts or "\\" in name
                or "\x00" in name or mode not in (0, 0o100000, 0o040000)
                or info.flag_bits & 0x1):
            raise HTTPException(422, "Unsafe archive entry")
        if name in seen:
            raise HTTPException(422, "Duplicate archive entry")
        seen.add(name)
        if not path.parts or path.parts[0] != "NatqAIAndroid":
            raise HTTPException(422, "Unexpected project layout")
        if info.is_dir():
            continue
        if info.file_size < 0 or info.file_size > MAX_UNPACKED:
            raise HTTPException(413, "Unpacked source too large")
        if info.file_size > 1024 * 1024 and info.compress_size == 0:
            raise HTTPException(422, "Invalid compressed archive entry")
        if info.compress_size and info.file_size / info.compress_size > MAX_COMPRESSION_RATIO:
            raise HTTPException(422, "Archive compression ratio is too high")
        total += info.file_size
        if total > MAX_UNPACKED:
            raise HTTPException(413, "Unpacked source too large")
        # Only exact trusted build/template files and web assets are accepted.
        rel = path.parts[1:]
        rel_name = "/".join(rel)
        if rel_name in TRUSTED_TEMPLATE_FILES:
            if archive.read(info) != TRUSTED_TEMPLATE_FILES[rel_name].encode("utf-8"):
                raise HTTPException(422, "Modified Android build template is not allowed")
        elif not (len(rel) >= 5 and rel[:4] == ("app", "src", "main", "assets") and rel[4] == "www"):
            raise HTTPException(422, "Unexpected build or source file")
        if not rel:
            raise HTTPException(422, "Unexpected project layout")
        clean.append((info, rel))
    required = set(TRUSTED_TEMPLATE_FILES) | {"app/src/main/assets/www/index.html"}
    names = {"/".join(rel) for _, rel in clean}
    if not required.issubset(names):
        raise HTTPException(422, "Android source project is incomplete")
    if _toolchain_status() is None:
        raise HTTPException(503, "Android build toolchain is not ready")

    temp = tempfile.mkdtemp(prefix="natqai-apk-")
    root = Path(temp) / "project"
    root.mkdir(mode=0o700)
    success = False
    try:
        for info, rel in clean:
            target = root.joinpath(*rel)
            target.parent.mkdir(parents=True, exist_ok=True)
            written = 0
            with archive.open(info) as src, target.open("wb") as dst:
                while True:
                    chunk = src.read(64 * 1024)
                    if not chunk:
                        break
                    written += len(chunk)
                    if written > info.file_size or written > MAX_UNPACKED:
                        raise HTTPException(422, "Archive entry size does not match its metadata")
                    dst.write(chunk)
            if written != info.file_size:
                raise HTTPException(422, "Archive entry size does not match its metadata")
            target.chmod(0o600)
        env = {"PATH": os.environ.get("PATH", "/usr/local/bin:/usr/bin:/bin"),
               "ANDROID_HOME": os.environ.get("ANDROID_HOME", "/opt/android-sdk"),
               "ANDROID_SDK_ROOT": os.environ.get("ANDROID_SDK_ROOT", "/opt/android-sdk"),
               "HOME": temp, "GRADLE_USER_HOME": str(Path(temp) / ".gradle"),
               "JAVA_HOME": os.environ.get("JAVA_HOME", "/usr/lib/jvm/java-17-openjdk-amd64"),
               "LANG": "C.UTF-8", "TMPDIR": temp}
        log_path = Path(temp) / "gradle-build.log"
        try:
            result = await _run_gradle_build(root, env, log_path, request)
        except _BuildClientDisconnected:
            # The caller has gone away; cleanup is handled by the outer finally block.
            raise HTTPException(499, "Build client disconnected")
        if result.returncode != 0:
            # Build logs stay inside the disposable worker and are never returned to clients.
            raise HTTPException(422, "Android build failed. Check Android SDK/Gradle compatibility.")
        apk = root / "app/build/outputs/apk/debug/app-debug.apk"
        if not apk.is_file() or not 1024 <= apk.stat().st_size <= MAX_APK_SIZE:
            raise HTTPException(500, "Build completed without a valid APK")
        _validate_apk(apk)
        _verify_apk_signature(apk)
        success = True
        return CleanupFileResponse(apk, media_type="application/vnd.android.package-archive",
                                   filename="natqai-debug.apk", cleanup_dir=temp)
    finally:
        if not success:
            shutil.rmtree(temp, ignore_errors=True)

def _validate_apk(apk: Path):
    """Check APK ZIP integrity, bounded contents, and Android binary entry signatures."""
    try:
        with zipfile.ZipFile(apk) as bundle:
            infos = bundle.infolist()
            if not infos or len(infos) > MAX_APK_ENTRIES:
                raise HTTPException(500, "Build output has an invalid APK entry count")
            names = set()
            unpacked = 0
            for info in infos:
                name = info.filename
                path = PurePosixPath(name)
                mode = (info.external_attr >> 16) & 0o170000
                if (path.is_absolute() or ".." in path.parts or "\\" in name
                        or name in names or mode not in (0, 0o100000, 0o040000)
                        or info.flag_bits & 0x1):
                    raise HTTPException(500, "Build output contains an unsafe APK entry")
                names.add(name)
                unpacked += info.file_size
                if unpacked > MAX_APK_UNPACKED:
                    raise HTTPException(500, "Build output expands beyond the APK size limit")
                if info.file_size > 1024 * 1024 and info.compress_size == 0:
                    raise HTTPException(500, "Build output contains an invalid compressed entry")
                if info.compress_size and info.file_size / info.compress_size > MAX_COMPRESSION_RATIO:
                    raise HTTPException(500, "Build output has an excessive compression ratio")
            bad = bundle.testzip()
            if bad:
                raise HTTPException(500, "Build output contains a corrupt APK entry")
            if not {"AndroidManifest.xml", "classes.dex"}.issubset(names):
                raise HTTPException(500, "Build output is missing required Android APK entries")
            manifest = bundle.read("AndroidManifest.xml")
            dex = bundle.read("classes.dex")
    except HTTPException:
        raise
    except (OSError, zipfile.BadZipFile, KeyError, RuntimeError):
        raise HTTPException(500, "Build output is not a readable APK archive")
    if len(manifest) < 8 or manifest[:4] != b"\x03\x00\x08\x00":
        raise HTTPException(500, "Build output has an invalid Android binary manifest")
    if len(dex) < 8 or not (dex.startswith(b"dex\n") and dex[7:8] == b"\x00"):
        raise HTTPException(500, "Build output has an invalid Dalvik executable")



def _verify_apk_signature(apk: Path):
    """Require a valid APK signature using the Android SDK's apksigner."""
    sdk = Path(os.environ.get("ANDROID_HOME", "/opt/android-sdk"))
    build_tools = sdk / "build-tools"
    versions = sorted(
        (p for p in build_tools.iterdir() if p.is_dir() and p.name.startswith("35.")),
        key=lambda p: tuple(int(part) if part.isdigit() else 0 for part in p.name.split(".")),
        reverse=True,
    ) if build_tools.is_dir() else []
    apksigner = next((p / "apksigner" for p in versions if (p / "apksigner").is_file()), None)
    if apksigner is None:
        raise HTTPException(503, "Android APK signature verifier is unavailable")
    try:
        result = subprocess.run(
            [str(apksigner), "verify", "--verbose", "--print-certs", str(apk)],
            capture_output=True, text=True, timeout=20, check=False,
            env={"PATH": os.environ.get("PATH", "/usr/bin:/bin"),
                 "ANDROID_HOME": str(sdk), "ANDROID_SDK_ROOT": str(sdk),
                 "LANG": "C.UTF-8"},
        )
    except (OSError, subprocess.TimeoutExpired):
        raise HTTPException(500, "APK signature verification could not be completed")
    if result.returncode != 0:
        raise HTTPException(500, "Built APK does not have a valid Android signature")

def _limits():
    resource.setrlimit(resource.RLIMIT_CPU, (600, 610))
    resource.setrlimit(resource.RLIMIT_FSIZE, (MAX_APK_SIZE, MAX_APK_SIZE))
    resource.setrlimit(resource.RLIMIT_NOFILE, (128, 128))
    if hasattr(resource, "RLIMIT_NPROC"):
        resource.setrlimit(resource.RLIMIT_NPROC, (128, 128))
