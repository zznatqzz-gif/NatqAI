class BuildRequestSizeLimitMiddleware:
    """Bound uploads and concurrent build requests before multipart spooling."""

    def __init__(self, application, max_bytes: int, max_concurrent_builds: int = 1):
        self.application = application
        self.max_bytes = max_bytes
        self.max_concurrent_builds = max_concurrent_builds
        self._active_builds = 0
        self._active_lock = threading.Lock()

    async def __call__(self, scope, receive, send):
        is_build = (scope.get("type") == "http" and scope.get("path") == "/build"
                    and scope.get("method") == "POST")
        if not is_build:
            await self.application(scope, receive, send)
            return

        with self._active_lock:
            if self._active_builds >= self.max_concurrent_builds:
                await self._reject(send, 429, "Another APK build is already running", retry_after=True)
                return
            self._active_builds += 1

        try:
            content_length = None
            for key, value in scope.get("headers", []):
                if key.lower() == b"content-length":
                    try:
                        content_length = int(value)
                    except (TypeError, ValueError):
                        content_length = None
                    break
            if content_length is not None and (content_length < 0 or content_length > self.max_bytes):
                await self._reject(send, 413, "Build request too large")
                return

            received = 0

            async def limited_receive():
                nonlocal received
                message = await receive()
                if message.get("type") == "http.request":
                    received += len(message.get("body", b""))
                    if received > self.max_bytes:
                        raise _BuildRequestTooLarge()
                return message

            try:
                await self.application(scope, limited_receive, send)
            except _BuildRequestTooLarge:
                await self._reject(send, 413, "Build request too large")
        finally:
            with self._active_lock:
                self._active_builds -= 1

    async def _reject(self, send, status: int, detail: str, retry_after: bool = False):
        import json
        body = json.dumps({"detail": detail}).encode("utf-8")
        headers = [(b"content-type", b"application/json"),
                   (b"content-length", str(len(body)).encode("ascii"))]
        if retry_after:
            headers.append((b"retry-after", b"5"))
        await send({"type": "http.response.start", "status": status, "headers": headers})
        await send({"type": "http.response.body", "body": body})


class _BuildRequestTooLarge(Exception):
    pass


